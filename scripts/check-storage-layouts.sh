#!/usr/bin/env bash
#
# Storage layout CI gate.
#
# Compares the current `forge inspect <Contract> storageLayout` output against a
# committed golden fixture under test/fixtures/storage-layouts/. Any drift fails
# the build.
#
# Rationale: Solidity storage layout is load-bearing for upgradeable proxies.
# Changes to storage-contract inheritance order, field insertions, or type
# widths all manifest as layout shifts. This script catches any such shift at
# PR time, before merge.
#
# Normalization: AST IDs inside `t_struct(...)NN_storage` and similar keys
# change on every unrelated source edit. Both this script and
# update-storage-layouts.sh apply the shared `normalize` function (see
# scripts/_normalize-storage-layout.sh) so the committed fixture is stable
# and Foundry tests that read it can pin stripped keys.
#
# Regenerating goldens (after an intentional layout change):
#   ./scripts/update-storage-layouts.sh
# then commit the diff under test/fixtures/storage-layouts/.
#
# Scope: the fixture is regenerated by the workflow above, so this gate catches
# "changed the layout and forgot to regenerate", not "changed the layout in a
# way that is unsafe for the live proxy". The append-only check against the
# deployed implementation's layout is test/StorageLayoutOnchainAnchor.t.sol.
#
# Exit codes: 0 = layouts match. 1 = layout regression (or a missing/empty
# fixture). 2 = the gate could not run (missing tool, build failure, forge
# inspect failure). deploy/08 reports 1 as a regression and any other non-zero
# exit as "could not run"; deploy/04 reports any non-zero exit as a regression,
# and this script's own output tells 2 from 1.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=_normalize-storage-layout.sh
source "$SCRIPT_DIR/_normalize-storage-layout.sh"

# Required tools. Missing these produces a clearer error than a pipe failure.
command -v jq >/dev/null 2>&1 || { echo "ERROR: 'jq' is required. Install via apt/brew."; exit 2; }
command -v forge >/dev/null 2>&1 || { echo "ERROR: 'forge' is required. See https://getfoundry.sh"; exit 2; }
# Log versions to CI output for debugging dev/CI divergence.
echo "Using $(jq --version) and $(forge --version 2>/dev/null | head -1)"

CONTRACTS=("VeHemi" "VeHemiVoteDelegation" "VeHemiAragonAdapter")
FIXTURES_DIR="test/fixtures/storage-layouts"
WORKDIR=$(mktemp -d)
trap 'rm -rf "$WORKDIR"' EXIT
FAILED=0

# --- Coverage guard ------------------------------------------------------
# CONTRACTS is hand-maintained. Any concrete contract that inherits an
# upgradeable storage chain but is missing from the list would be silently
# ungated. Discover them from source and require an explicit entry.
# Each file is flattened onto one line with both comment forms stripped first:
# `contract VeHemi is` wraps its inheritance list over several lines, which a
# line-oriented grep cannot see. Abstract contracts (the storage chain itself)
# are excluded explicitly, and the transitive closure over concrete contracts
# also finds a successor that reaches the chain through `is VeHemi`.
# Not discovered: a contract that reaches the chain through an aliased import
# (`import {VeHemiStorageV3 as S}; contract X is S`).
_storage_chain_flat_sources() {
  # Strip BOTH comment forms with a state machine (a `/* ... */` NatSpec block
  # that merely ILLUSTRATES a declaration must not be discovered), then join
  # each file onto one line so a wrapped inheritance list stays visible.
  find src -name '*.sol' -print0 | xargs -0 -r awk '
    FNR == 1 && NR > 1 { printf "\n" }
    {
      line = $0; out = ""; i = 1
      while (i <= length(line)) {
        c2 = substr(line, i, 2)
        if (inblk)       { if (c2 == "*/") { inblk = 0; i += 2 } else { i++ } }
        else if (c2 == "/*") { inblk = 1; i += 2 }
        else if (c2 == "//") { break }
        else { out = out substr(line, i, 1); i++ }
      }
      printf "%s ", out
    }
    END { printf "\n" }'
}
_storage_chain_contract_bases() {
  _storage_chain_flat_sources \
    | grep -oE '(abstract[[:space:]]+)?contract[[:space:]]+[A-Za-z0-9_]+[[:space:]]+is[[:space:]][^{;]*' \
    | grep -v '^abstract' \
    | sed -E 's/^contract[[:space:]]+([A-Za-z0-9_]+)[[:space:]]+is[[:space:]]/\1\t/'
}
_storage_chain_discover() {
  local chain_pattern='VeHemiStorageV[0-9]+|VeHemiDelegationStorageV[0-9]+'
  local contract_bases discovered="" prev="" n m bases
  contract_bases="$(_storage_chain_contract_bases)"
  while :; do
    discovered="$( { printf '%s\n' "$discovered"
                     while IFS=$'\t' read -r n bases; do
                       [ -n "$n" ] || continue
                       if printf '%s' "$bases" \
                            | grep -qE "(^|[^A-Za-z0-9_])($chain_pattern)([^A-Za-z0-9_]|$)"; then
                         printf '%s\n' "$n"
                       fi
                     done <<< "$contract_bases"
                   } | sed '/^$/d' | sort -u )"
    [ "$discovered" = "$prev" ] && break
    prev="$discovered"
    for m in $discovered; do chain_pattern="$chain_pattern|$m"; done
  done
  printf '%s\n' "$discovered" | sed '/^$/d'
}
DISCOVERED=()
while IFS= read -r name; do
  [ -n "$name" ] && DISCOVERED+=("$name")
done < <(_storage_chain_discover)
# A discovery predicate that matches nothing is broken, not clean: fail closed.
if [ "${#DISCOVERED[@]}" -eq 0 ]; then
  echo "ERROR: the storage-chain discovery predicate matched NO contract under src/."
  echo "       Either it is broken or the storage contracts were renamed."
  echo "       This coverage check is VACUOUS until that is fixed. Not a pass."
  FAILED=1
fi
for d in "${DISCOVERED[@]}"; do
  found=0
  for c in "${CONTRACTS[@]}"; do [ "$c" = "$d" ] && found=1; done
  if [ "$found" -eq 0 ]; then
    echo "ERROR: '$d' inherits an upgradeable storage chain but is not in CONTRACTS."
    echo "       Add it to scripts/check-storage-layouts.sh AND to"
    echo "       scripts/update-storage-layouts.sh, then regenerate fixtures."
    FAILED=1
  fi
done

# `forge inspect <C> storageLayout` reads the layout out of the compilation
# artifact and exits 1 ("storage layout missing from artifact") after an
# incremental build. Clean first, and report a tooling failure as exit 2 with
# forge's own error, never as a silent layout regression.
echo "Running 'forge clean && forge build' so every artifact carries a storage layout..."
forge clean >/dev/null 2>&1 || true
if ! forge build >/dev/null 2>&1; then
  echo "ERROR: 'forge build' failed; the storage-layout gate COULD NOT RUN."
  echo "       This is NOT a layout regression."
  exit 2
fi

for c in "${CONTRACTS[@]}"; do
  golden="$FIXTURES_DIR/$c.json"
  # `-s`, not `-f`: a zero-byte fixture must fail, not be diffed against.
  if [ ! -s "$golden" ]; then
    echo "ERROR: Missing or EMPTY golden fixture: $golden"
    echo "       Run scripts/update-storage-layouts.sh to create it."
    FAILED=1
    continue
  fi

  if ! forge inspect "$c" storageLayout --json 2>"$WORKDIR/err-$c" > "$WORKDIR/raw-$c.json"; then
    echo "ERROR: 'forge inspect $c storageLayout' failed; the gate COULD NOT RUN for $c."
    sed 's/^/       /' "$WORKDIR/err-$c"
    echo "       This is NOT a layout regression. Try 'forge clean && forge build'."
    exit 2
  fi
  if [ ! -s "$WORKDIR/raw-$c.json" ] || [ "$(jq -r '.storage | length' "$WORKDIR/raw-$c.json" 2>/dev/null)" = "null" ]; then
    echo "ERROR: 'forge inspect $c storageLayout' produced no usable layout for $c."
    echo "       This is NOT a layout regression."
    exit 2
  fi
  normalize < "$WORKDIR/raw-$c.json" > "$WORKDIR/current-$c.json"
  # Committed fixtures are already normalized by update-storage-layouts.sh,
  # so normalizing again is a no-op but makes the script tolerant to old
  # pre-normalized fixtures during the migration window.
  normalize < "$golden" > "$WORKDIR/golden-$c.json"

  if ! diff -u "$WORKDIR/golden-$c.json" "$WORKDIR/current-$c.json"; then
    echo ""
    echo "ERROR: Storage layout regression detected in $c"
    echo "       If the change is intentional, regenerate the golden fixture:"
    echo "         ./scripts/update-storage-layouts.sh"
    echo "       Then inspect the diff under test/fixtures/storage-layouts/ and"
    echo "       ensure it is append-only: no existing slot shifted, no existing"
    echo "       type changed, AND no struct gained or lost a member. A member"
    echo "       appended into a struct's free padding moves neither the slot"
    echo "       map nor numberOfBytes and is invisible to THIS diff once the"
    echo "       fixture is regenerated — the machine checks for that class are"
    echo "       the member-count pins in"
    echo "       test/StorageLayoutGolden.t.sol plus"
    echo "       test/StorageLayoutOnchainAnchor.t.sol."
    FAILED=1
  else
    echo "OK: $c storage layout matches golden fixture"
  fi
done

exit $FAILED
